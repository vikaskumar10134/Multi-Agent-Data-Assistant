from pydantic import BaseModel , Field
from typing import Annotated , List , Literal

import operator

class JudgeSchema(BaseModel):
    is_safe : bool = Field(... , description=(
        "Indicates whether the query is safe to execute. "
        "Returns True only if the query does not contain any "
        "DELETE, UPDATE, INSERT, DROP, ALTER, TRUNCATE, or other "
        "database-modifying operations; otherwise returns False."
    ))
    comments : str = Field(... , description='Additional comments or feedback from the judge regarding the SQL query')

class AgentSchema(BaseModel):
    messages : Annotated[List , operator.add] = Field(... , description='List of messages to be processed by the agent')
    user_question : str = Field(... , description='The original question asked by the user')
    curated_ques : str = Field(... , description='Curated user question')
    
    judge_query : JudgeSchema = Field(... , description='')
    generated_sql_query : str = Field(... , description='The SQL query generated by the agent based on the curated question and prompt context')
    sql_query_execution_result  : str = Field(... , description='The result of executing the generated SQL query on the database')
    final_answer : str = Field(... , description='The final answer generated by the agent based on the SQL query execution result and the curated question')

class ETLAgentSchema(BaseModel):
    messages : Annotated[list , operator.add] = Field(... , description='List of messages to be processed by the ETL agent')


class RouterSchema(BaseModel):
    answer : Literal['sql' , 'etl'] = Field(... , description='''
        Choose "sql" when the user wants to query, retrieve, filter,
        aggregate, or inspect data that already exists in a database.

        Choose "etl" when the user wants to extract, transform, clean,
        load, ingest, or move data between external sources and databases.

        Rule: Existing database data → "sql".
        Data ingestion or movement → "etl".

        

''')
    comments : str = Field(... , description='Provide the reason why choose this values')


class DataAgentSchema(BaseModel):
    messages : Annotated[list , operator.add] = Field(... , description='List of messages to be processed by the agent')
    route_response : str = Field(... , description='List of messages to be processed by the Data agent')